// Turns the static catalogue (public/data/*.json) into supabase/seed.sql, so the database and the site never disagree
// about which foods, challenges and badges exist. Run with: npm run db:seed
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`)
const n = (v) => (v === null || v === undefined ? 'null' : String(Number(v)))
const j = (v) => `${q(JSON.stringify(v))}::jsonb`

const upsert = (table, cols, rows, key = 'id') => {
  if (rows.length === 0) return ''
  const set = cols.filter((c) => c !== key).map((c) => `${c} = excluded.${c}`).join(', ')
  return `insert into public.${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${r.join(', ')})`).join(',\n')}\non conflict (${key}) do update set ${set};\n`
}

export function buildSeed({ foods, challenges, badges, quiz = [] }) {
  const foodCols = ['id', 'name_bn', 'name_en', 'description_bn', 'description_en', 'category', 'scope', 'district_en', 'district_bn', 'division', 'xp', 'image_url', 'image_attribution', 'source_url', 'verification_status', 'association_confidence']
  const foodRows = foods.map((f) => [q(f.id), q(f.name_bn), q(f.name_en), q(f.description_bn), q(f.description_en), q(f.category), q(f.scope), q(f.region?.district_en), q(f.region?.district_bn), q(f.region?.division), n(f.xp), q(f.image_url), q(f.image_attribution), q(f.source_url), q(f.verification_status), q(f.association_confidence)])
  const chCols = ['id', 'challenge_type', 'title_bn', 'title_en', 'description_bn', 'description_en', 'rules', 'xp_reward', 'is_active']
  const chRows = challenges.map((c) => [q(c.id), q(c.challenge_type), q(c.title_bn), q(c.title_en), q(c.description_bn), q(c.description_en), j(c.rules), n(c.xp_reward), c.is_active ? 'true' : 'false'])
  const bCols = ['id', 'name_bn', 'name_en', 'description_bn', 'description_en', 'unlock_rule']
  const bRows = badges.map((b) => [q(b.id), q(b.name_bn), q(b.name_en), q(b.description_bn), q(b.description_en), j(b.unlock_rule)])
  return [
    '-- GENERATED by scripts/seed.mjs from public/data/*.json. Do not edit by hand; run `npm run db:seed`.',
    '',
    upsert('foods', foodCols, foodRows),
    upsert('challenges', chCols, chRows),
    upsert('badges', bCols, bRows),
    upsert('quiz_questions', ['id', 'correct'], quiz.map((x) => [q(x.id), n(x.correct)])),
  ].join('\n')
}

export const loadCatalogue = (dir = 'public/data') => ({
  foods: JSON.parse(readFileSync(`${dir}/foods.json`, 'utf8')),
  challenges: JSON.parse(readFileSync(`${dir}/challenges.json`, 'utf8')),
  badges: JSON.parse(readFileSync(`${dir}/badges.json`, 'utf8')),
  quiz: JSON.parse(readFileSync(`${dir}/quiz.json`, 'utf8')),
})

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync('supabase/seed.sql', buildSeed(loadCatalogue()))
  console.log('wrote supabase/seed.sql')
}
